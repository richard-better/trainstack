const directory = new URL("../apps/prehab/PrehabKit/Sources/PrehabCore/Contract/", import.meta.url);
await mkdir(directory, { recursive: true });
type Schema = Record<string, any>;
const capital = (value: string) => value[0]!.toUpperCase() + value.slice(1);
function swift(schema: Schema, name: string, declarations: string[]): string {
  if (schema.anyOf) {
    const choices = schema.anyOf.filter((s: Schema) => s.type !== "null");
    if (choices.length === 1)
      return (
        swift(choices[0], name, declarations) + (choices.length !== schema.anyOf.length ? "?" : "")
      );
    return "JSONValue";
  }
  if (Array.isArray(schema.type))
    return (
      swift(
        { ...schema, type: schema.type.find((t: string) => t !== "null") },
        name,
        declarations,
      ) + "?"
    );
  if (schema.type === "array") return `[${swift(schema.items, name + "Item", declarations)}]`;
  if (schema.type === "string") return "String";
  if (schema.type === "integer") return "Int";
  if (schema.type === "number") return "Double";
  if (schema.type === "boolean") return "Bool";
  if (schema.type !== "object") return "JSONValue";
  if (!schema.properties) return "[String: JSONValue]";
  const fields = Object.entries(schema.properties).map(([key, value]) => {
    let type = swift(value as Schema, name + capital(key), declarations);
    if (!schema.required?.includes(key) && !type.endsWith("?")) type += "?";
    return { key, type };
  });
  const identifiable = fields.some((f) => f.key === "id" && f.type === "String");
  declarations.push(
    `public struct ${name}: Codable, Hashable, Sendable${identifiable ? ", Identifiable" : ""} {\n${fields.map((f) => `  public var \`${f.key}\`: ${f.type}`).join("\n")}\n  public init(${fields.map((f) => `${f.key}: ${f.type}${f.type.endsWith("?") ? " = nil" : ""}`).join(", ")}) {\n${fields.map((f) => `    self.${f.key} = ${f.key}`).join("\n")}\n  }\n}`,
  );
  return name;
}
const endpointLines: string[] = [];
async function walk(node: any, path: string[] = []) {
  if (node["~orpc"]) {
    const name = path.map(capital).join("") + "Output";
    const declarations: string[] = [];
    const type = swift(
      z.toJSONSchema(node["~orpc"].outputSchema, { unrepresentable: "any" }),
      name,
      declarations,
    );
    if (type !== name) declarations.push(`public typealias ${name} = ${type}`);
    await writeFile(
      new URL(name + ".swift", directory),
      "// Generated by scripts/generate-prehab-contract.ts. Do not edit.\n" +
        declarations.join("\n\n") +
        "\n",
    );
    endpointLines.push(
      `  public static let ${path[0] + path.slice(1).map(capital).join("")} = Endpoint<${name}>("${path.join("/")}")`,
    );
  } else for (const [key, child] of Object.entries(node)) await walk(child, [...path, key]);
}
await walk(contract);
await writeFile(
  new URL("Endpoints.swift", directory),
  `// Generated by scripts/generate-prehab-contract.ts. Do not edit.\npublic enum Endpoints {\n${endpointLines.join("\n")}\n}\n`,
);
await writeFile(
  new URL("../apps/prehab/PrehabKit/Sources/PrehabUI/Resources/onboarding.json", import.meta.url),
  JSON.stringify(
    OnboardingFlow.map((id) => ({
      id,
      title: QUESTIONS[id].title,
      skippable: QUESTIONS[id].skippable,
      schema: z.toJSONSchema(QUESTIONS[id].answerSchema),
    })),
    null,
    2,
  ),
);
execFileSync("swift", ["format", "--in-place", "--recursive", directory.pathname]);

